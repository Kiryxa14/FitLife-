print(f"Рады видеть вас, {user_name}!")
user_age = int(input("Пожалуйста, введите ваш возраст: "))
print(f"Приятно познакомиться, {user_name}! Вам {user_age} года.")
print(f"Давайте рассчитаем ваш индекс массы тела (BMI) и норму воды, чтобы оценить ваше здоровье.")
user_height = float(input("Пожалуйста, введите ваш рост в метрах (например 1.75): "))
user_weight = float(input("Пожалуйста, введите ваш вес в килограммах (например 70): "))
bmi = user_weight / (user_height ** 2)
bmi = round(bmi, 1)
water_ml = user_weight * 30
water_l = water_ml / 1000
water_l = round(water_l, 1)
print(f"Отчет для пользователя {user_name}, {user_age} года:")
print(f"Твой индекс массы тела (BMI): {bmi:.1f}")
print(f"Рекомендуемая нормы воды: {water_l:.1f} литра в день.")
